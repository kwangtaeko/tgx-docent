import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import JSZip from 'jszip';
import { renderSite } from '../../skills/docent/scripts/src/renderers/html.mjs';
import { LANGUAGES, stringsFor } from '../../skills/docent/scripts/src/renderers/i18n.mjs';
import { renderPptx } from '../../skills/docent/scripts/src/renderers/pptx.mjs';
import { renderPrint } from '../../skills/docent/scripts/src/renderers/print.mjs';
import { renderReadme } from '../../skills/docent/scripts/src/renderers/readme.mjs';
import { loadGolden } from '../helpers/golden.mjs';

// 산출물 고정 문구(골든 데이터 자체의 한국어는 빼고 확인)
const KO_LABELS = ['화면 목록', '입력 항목', '버튼과 동작', '안내 메시지', '주요 기능', '사용자 역할', '메뉴 구조', '기준일', '소스 파일', '확인 필요'];

async function english(preset = 'handover') {
  const input = await loadGolden();
  input.options = { preset, formats: ['html'], language: 'en', title: 'User Manual', organization: '', revisions: [] };
  input.media = { images: new Set(['orders-new']), gifs: new Set(['orders-new']) };
  return input;
}

test('언어별 문구 표의 키가 같다', () => {
  const keys = (o) => Object.keys(o).sort();
  for (const lang of LANGUAGES) assert.deepEqual(keys(stringsFor(lang)), keys(stringsFor('ko')), lang);
  for (const group of ['types', 'typesShort']) assert.deepEqual(keys(stringsFor('en')[group]), keys(stringsFor('ko')[group]));
});

test('영어 HTML: lang="en", 영어 문구, 한국어 고정 문구 없음', async () => {
  for (const preset of ['handover', 'delivery', 'portfolio']) {
    const files = renderSite(await english(preset));
    for (const [name, html] of files) {
      if (!name.endsWith('.html')) continue;
      assert.match(html, /<html lang="en">/, name);
      for (const ko of KO_LABELS) assert.ok(!html.includes(`>${ko}<`), `${preset} ${name}: ${ko}`);
      assert.ok(!html.includes('docent로 생성한'), name);
    }
    const index = files.get('index.html');
    assert.match(index, /Key features/);
    assert.match(index, /Draft generated by docent · As of 2026-10-13/);
  }
  const screen = renderSite(await english()).get('screens/orders-new.html');
  for (const label of ['Input fields', 'Buttons and actions', 'Messages', 'Required', 'Source files']) assert.ok(screen.includes(label), label);
});

test('영어 README·인쇄용 HTML', async () => {
  const input = await english();
  const readme = renderReadme(input);
  assert.match(readme, /^## Key features$/m);
  assert.match(readme, /Draft generated by docent from the source code \(as of 2026-10-13\)/);
  assert.ok(!readme.includes('## 주요 기능'));
  const print = renderPrint(input);
  assert.match(print, /<html lang="en">/);
  assert.match(print, /<title>nextjs-sample User Manual<\/title>/);
});

test('영어 PPTX', async () => {
  const input = await english('delivery');
  const zip = await JSZip.loadAsync(await renderPptx(input, { mediaDir: await mkdtemp(join(tmpdir(), 'docent-media-')) }));
  const slides = await Promise.all(Object.keys(zip.files).filter((n) => /^ppt\/slides\/slide\d+\.xml$/.test(n)).map((n) => zip.file(n).async('string')));
  const all = slides.join(' ');
  for (const label of ['Overview', 'Menu structure', 'Workflows · ', 'Revision history', 'As of 2026-10-13']) assert.ok(all.includes(label), label);
  for (const ko of ['소개', '메뉴 구조', '개정 이력', '기준일']) assert.ok(!all.includes(`>${ko}<`), ko);
});
